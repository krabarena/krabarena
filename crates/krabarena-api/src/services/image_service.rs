//! Direct image upload pipeline. Used by:
//!   - `POST /v1/images` — generic authenticated upload that returns
//!     `{ url, suggested_alt, markdown }`. Authors paste the ready-to-
//!     use markdown line into their Claim body. No DB tracking, no
//!     `img-<id>` indirection — image metadata lives in the markdown
//!     itself.
//!   - `POST /v1/battles/{id}/cover-image` — Battle hero image,
//!     stored on `battles.cover_image_url` / `cover_image_alt`.
//!
//! Distinct from the bundle-extraction pipeline in `claim_media.rs`:
//! the input here is a raw image POSTed via `multipart/form-data`,
//! not a tarball entry. The accepted formats whitelist is tighter
//! too — PNG / JPEG / WebP only, no animated GIF, no SVG (would let
//! a malicious upload smuggle inline `<script>` past the markdown
//! sanitizer).
//!
//! Pipeline per upload:
//!   1. MIME-sniff the first few bytes — reject anything that isn't
//!      one of the three whitelisted raster formats.
//!   2. Size cap at 2 MB. Larger uploads typically belong inside the
//!      artifact bundle anyway (where the 1 MB per-image cap and
//!      bundle-level dedup apply).
//!   3. SHA-256 the bytes, upload to GCS at `images/<sha>.<ext>`.
//!      Content-addressable, so two callers uploading the same image
//!      dedup at the bucket level.
//!   4. (Optional) Call Gemini Vision to produce a 1-2 sentence alt
//!      text. Failure here is non-fatal — the upload still succeeds
//!      with a filename-derived alt as fallback.

use base64::Engine;
use base64::engine::general_purpose::STANDARD as B64;
use sha2::{Digest, Sha256};

use crate::error::ApiError;
use crate::services::artifact_service;
use crate::services::gemini_service::{self, GeminiClient, GeminiError};

/// 2 MB — comfortable headroom for screenshots, charts, and photos
/// at typical document-display resolutions. Above this the image
/// belongs in the artifact bundle (where the bundle pipeline applies
/// its own caps + Vision moderation).
pub const MAX_IMAGE_BYTES: usize = 2 * 1024 * 1024;

/// Result of a successful upload. `suggested_alt` is the alt-text
/// generated by Gemini Vision (or filename-derived when Vision is
/// unavailable / fails). The caller decides what to do with it —
/// the generic `POST /v1/images` handler bakes it into a ready-to-
/// paste markdown snippet; the Battle cover handler stores it on
/// `battles.cover_image_alt`.
#[derive(Debug, Clone)]
pub struct UploadedImage {
    pub url: String,
    pub suggested_alt: String,
    pub sha256: String,
    pub mime_type: &'static str,
    pub bytes: i64,
}

/// Validate, upload, and (optionally) caption an uploaded image.
///
/// `filename` is the multipart-supplied name (used only for the
/// filename-derived alt-text fallback; never stored). `gemini` is
/// the shared client — when `None` or the API key is unset, alt
/// text falls back to filename. Vision failures (network, rate
/// limit, parse) also fall back without surfacing an error to the
/// caller; the upload itself isn't blocked on captioning.
pub async fn upload_image(
    blob_store_url: &str,
    gemini: Option<&GeminiClient>,
    bytes: &[u8],
    filename: Option<&str>,
) -> Result<UploadedImage, ApiError> {
    if bytes.is_empty() {
        return Err(ApiError::ClaimMissingArtifact);
    }
    if bytes.len() > MAX_IMAGE_BYTES {
        return Err(ApiError::ClaimMediaTooLarge {
            path: filename.unwrap_or("uploaded image").to_string(),
        });
    }

    let (mime, ext) =
        sniff_image_mime(bytes).ok_or_else(|| ApiError::ClaimMediaUnsupportedType {
            path: filename.unwrap_or("uploaded image").to_string(),
        })?;

    // Hash the raw bytes for the bucket object name (content-
    // addressable, dedupes identical uploads across callers).
    let hash_hex = hex::encode(Sha256::digest(bytes));
    let object_name = format!("images/{}.{}", hash_hex, ext);
    let sha256 = format!("sha256:{}", hash_hex);

    let url = upload_to_gcs_or_dev(blob_store_url, &object_name, mime, bytes).await?;

    // Alt text: try Vision first (when configured), fall back to
    // filename. Never block the upload on a Vision failure.
    let suggested_alt = match gemini {
        Some(g) if g.is_configured() => match generate_alt_text(g, mime, bytes).await {
            Ok(caption) if !caption.trim().is_empty() => caption,
            Ok(_) => alt_from_filename(filename),
            Err(e) => {
                tracing::warn!(error = %e, "image_service: Vision alt-text fallback to filename");
                alt_from_filename(filename)
            }
        },
        _ => alt_from_filename(filename),
    };

    Ok(UploadedImage {
        url,
        suggested_alt,
        sha256,
        mime_type: mime,
        bytes: bytes.len() as i64,
    })
}

/// MIME-sniff by magic-bytes. Tight whitelist: PNG, JPEG, WebP.
/// Returns `(content_type, file_extension)` for each accepted
/// format. Animated GIF and SVG are intentionally rejected — see
/// the module doc.
pub fn sniff_image_mime(bytes: &[u8]) -> Option<(&'static str, &'static str)> {
    if bytes.len() < 12 {
        return None;
    }
    // PNG: 89 50 4E 47 0D 0A 1A 0A
    if bytes.starts_with(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A]) {
        return Some(("image/png", "png"));
    }
    // JPEG: FF D8 FF
    if bytes.starts_with(&[0xFF, 0xD8, 0xFF]) {
        return Some(("image/jpeg", "jpg"));
    }
    // WebP: RIFF????WEBP — bytes[0..4]="RIFF", bytes[8..12]="WEBP"
    if &bytes[0..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        return Some(("image/webp", "webp"));
    }
    None
}

/// Derive a readable alt-text from the upload filename.
///
/// Strips the extension, replaces separators with spaces, and
/// trims. Empty / None → `"image"` so the alt tag is never blank
/// (screen readers prefer "image" over "" when there's no caption).
pub fn alt_from_filename(filename: Option<&str>) -> String {
    let name = filename.unwrap_or("");
    let stem = name.rsplit_once('.').map(|(s, _)| s).unwrap_or(name).trim();
    if stem.is_empty() {
        return "image".to_string();
    }
    let cleaned: String = stem
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == ' ' {
                c
            } else {
                ' '
            }
        })
        .collect();
    let trimmed = cleaned.split_whitespace().collect::<Vec<_>>().join(" ");
    if trimmed.is_empty() {
        "image".to_string()
    } else {
        trimmed
    }
}

/// Upload bytes to GCS at the given object path, returning the
/// resolved public URL.
async fn upload_to_gcs_or_dev(
    blob_store_url: &str,
    object_name: &str,
    content_type: &'static str,
    bytes: &[u8],
) -> Result<String, ApiError> {
    if let Some(bucket) = blob_store_url.strip_prefix("gs://") {
        artifact_service::upload_bytes_to_gcs(bucket, object_name, content_type, bytes).await?;
        Ok(format!(
            "https://storage.googleapis.com/{}/{}",
            bucket, object_name,
        ))
    } else {
        // Dev fallback: build a URL but don't actually push. Same
        // strategy as artifact_service.
        tracing::warn!(
            object = %object_name,
            "image_service: dev mode, not actually uploading",
        );
        Ok(format!("{}/{}", blob_store_url, object_name))
    }
}

/// Ask Gemini Vision for a 1-2 sentence alt text. The prompt biases
/// toward what a screen-reader user needs: what the image shows, not
/// editorial commentary.
async fn generate_alt_text(
    gemini: &GeminiClient,
    mime: &'static str,
    bytes: &[u8],
) -> Result<String, GeminiError> {
    let api_key = gemini.api_key().ok_or(GeminiError::NoApiKey)?;
    let model = gemini.model();
    let url = format!(
        "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    );
    let prompt = "You are writing accessible alt text for an image. \
        Describe what the image shows in 1-2 short sentences. \
        If the image is a chart or graph, name the chart type and the \
        main quantity it compares. Do not start with phrases like \
        \"An image of\" or \"This image shows\" — just describe. \
        Plain text only, no markdown.";
    let b64 = B64.encode(bytes);
    let body = serde_json::json!({
        "contents": [{
            "role": "user",
            "parts": [
                { "text": prompt },
                { "inlineData": { "mimeType": mime, "data": b64 } }
            ]
        }],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 120,
        }
    });
    let resp =
        gemini_service::post_json_with_retry(gemini.http_client(), &url, &body, "image_alt", model)
            .await?;
    if !resp.status().is_success() {
        let status = resp.status().as_u16();
        let body = resp.text().await.unwrap_or_default();
        return Err(GeminiError::Status { status, body });
    }
    let json: serde_json::Value = resp
        .json()
        .await
        .map_err(|e| GeminiError::Parse(e.to_string()))?;
    let text = json
        .pointer("/candidates/0/content/parts/0/text")
        .and_then(|v| v.as_str())
        .ok_or_else(|| GeminiError::Parse("missing candidates[0].content.parts[0].text".into()))?;
    Ok(text.trim().to_string())
}

/// Escape `[` and `]` in alt text and assemble a ready-to-paste
/// markdown image reference. The caller (e.g. `POST /v1/images`) can
/// drop this directly into a response so authors don't have to
/// hand-build the snippet.
pub fn markdown_snippet(alt: &str, url: &str) -> String {
    let safe_alt = alt.replace(['[', ']'], "");
    format!("![{}]({})", safe_alt.trim(), url)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sniff_png_jpeg_webp() {
        let png = [0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A, 0, 0, 0, 0];
        assert_eq!(sniff_image_mime(&png), Some(("image/png", "png")));
        let jpg = [0xFF, 0xD8, 0xFF, 0xE0, 0, 0, 0, 0, 0, 0, 0, 0];
        assert_eq!(sniff_image_mime(&jpg), Some(("image/jpeg", "jpg")));
        let mut webp = Vec::from(b"RIFFsizeWEBP" as &[u8]);
        webp.extend_from_slice(&[0; 8]);
        assert_eq!(sniff_image_mime(&webp), Some(("image/webp", "webp")));
    }

    #[test]
    fn sniff_rejects_svg_and_gif() {
        // SVG: starts with `<?xml` or `<svg`
        let svg = b"<svg xmlns=\"http://www.w3.org/2000/svg\"></svg>";
        assert_eq!(sniff_image_mime(svg), None);
        // GIF: `GIF89a` — intentionally not in the whitelist
        let gif = b"GIF89a\x01\x00\x01\x00";
        assert_eq!(sniff_image_mime(gif), None);
    }

    #[test]
    fn sniff_rejects_short_input() {
        assert_eq!(sniff_image_mime(&[]), None);
        assert_eq!(sniff_image_mime(&[0x89, b'P', b'N']), None);
    }

    #[test]
    fn alt_from_filename_basic() {
        assert_eq!(alt_from_filename(Some("benchmark.png")), "benchmark");
        assert_eq!(
            alt_from_filename(Some("chart_with_dashes.png")),
            "chart with dashes",
        );
        assert_eq!(alt_from_filename(Some("a-b-c.jpg")), "a b c");
        assert_eq!(alt_from_filename(Some(".png")), "image");
        assert_eq!(alt_from_filename(None), "image");
        assert_eq!(alt_from_filename(Some("")), "image");
    }

    #[test]
    fn markdown_snippet_escapes_brackets() {
        // `[` and `]` inside alt text would break the surrounding
        // markdown link syntax; the helper must strip them.
        assert_eq!(
            markdown_snippet("foo [bar] baz", "https://x/y.png"),
            "![foo bar baz](https://x/y.png)"
        );
    }

    #[test]
    fn markdown_snippet_basic() {
        assert_eq!(
            markdown_snippet("Bar chart of TS vs Rust", "https://x/y.png"),
            "![Bar chart of TS vs Rust](https://x/y.png)"
        );
    }
}

-- 0.8.20 — claim card UX & short battle summary.
--
-- 1. `claims.updated_at` — "last engaged" timestamp. NOT a row-level
--    last-modified — bumped specifically when a claim accumulates
--    new ENGAGEMENT (verification/refutation/comment). Battle pages
--    sort claims by `updated_at DESC` so a freshly-engaged claim
--    floats to the top regardless of when it was originally posted.
--
--    On row creation: defaults to `NOW()` (= `created_at` for fresh
--    rows). The bumps live in `verification_service::create_verification`
--    and `comment_service::create_comment`.
--
--    Backfill for existing rows: GREATEST of created_at, the most
--    recent verification's created_at, and the most recent comment's
--    created_at. So legacy claims with old engagement still sort
--    sensibly out of the gate.
--
-- 2. `battles.short_summary` — a compact (~200 char + top-3 leaderboard)
--    version of the executive summary, generated by the same
--    `battle_summarizer` Gemini call as the full version. Rendered on
--    the home page / battle-list cards where the full editorial would
--    crowd the layout.
ALTER TABLE claims
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

UPDATE claims c
   SET updated_at = GREATEST(
       c.created_at,
       COALESCE((SELECT MAX(v.created_at) FROM verifications v WHERE v.claim_id = c.id), c.created_at),
       COALESCE((SELECT MAX(cm.created_at) FROM comments cm WHERE cm.claim_id = c.id), c.created_at)
   );

ALTER TABLE battles
    ADD COLUMN IF NOT EXISTS short_summary TEXT;
